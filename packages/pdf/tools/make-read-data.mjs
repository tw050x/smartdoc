// Builds read/data.js, the tables reading PDFs needs: the standard encodings (PDF 32000-1 Annex
// D), glyph names to Unicode (Adobe's glyph list, with the additions readers have long used),
// font-name tables (which names stand for the 14 standard fonts, which are serif or symbol fonts),
// and the 14 standard fonts' widths (Adobe's AFM files).
//
//   node tools/make-read-data.mjs <pdf.worker.mjs> <afm dir>
//
// The encodings, glyph names, font-name tables, CFF strings and bidirectional types are taken as transcribed in Mozilla's pdf.js
// (Apache License 2.0), so text comes out as other readers give it; the widths from Adobe's Core 14
// AFM files. Run it once; read/data.js is kept in the repository.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const [workerPath, afmDir] = process.argv.slice(2);
if (!workerPath || !afmDir) {
  console.error('Usage: node tools/make-read-data.mjs <pdf.worker.mjs> <afm dir>');
  process.exit(1);
}
const source = readFileSync(workerPath, 'utf8');

const arrayConst = (name) => {
  const m = source.match(new RegExp(`^const ${name} = (\\[.*\\]);$`, 'm'));
  if (!m) throw new Error(`${name} not found`);
  return JSON.parse(m[1]);
};
const lookupTable = (name, context = {}) => {
  const start = source.indexOf(`const ${name} = getLookupTableFactory(function (t) {`);
  if (start < 0) throw new Error(`${name} not found`);
  const bodyStart = source.indexOf('{', start + name.length + 40) + 1;
  const end = source.indexOf('\n});', bodyStart);
  const t = Object.create(null);
  vm.runInNewContext(source.slice(bodyStart, end), { t, ...context });
  return { ...t };
};

const bidiBase = arrayConst('baseTypes');
const bidiArabic = arrayConst('arabicTypes');
const encodings = Object.fromEntries(['StandardEncoding', 'WinAnsiEncoding', 'MacRomanEncoding', 'MacExpertEncoding', 'SymbolSetEncoding', 'ZapfDingbatsEncoding', 'ExpertEncoding'].map((n) => [n, arrayConst(n)]));
const glyphs = lookupTable('getGlyphsUnicode');
const dingbats = lookupTable('getDingbatsGlyphsUnicode');
const stdFontMap = lookupTable('getStdFontMap');
const nonStdFontMap = lookupTable('getNonStdFontMap');
const serifFonts = Object.keys(lookupTable('getSerifFonts'));
const symbolsFonts = Object.keys(lookupTable('getSymbolsFonts'));
const specialPua = lookupTable('getSpecialPUASymbols');
// Glyph indexes to code points in the standard fonts' usual glyph order, for composite fonts that
// aren't embedded and whose codes are glyph indexes (Arial, Times New Roman and the like), with
// the additions some fonts need, and the Macintosh standard order (Apple's TrueType 'post' table).
const glyphMaps = {
  standard: lookupTable('getGlyphMapForStandardFonts'),
  macOrdered: lookupTable('getGlyphMapForMacOrderedFonts', { getGlyphsUnicode: () => glyphs, MacStandardGlyphOrdering: arrayConst('MacStandardGlyphOrdering') }),
  arialBlack: lookupTable('getSupplementalGlyphMapForArialBlack'),
  calibri: lookupTable('getSupplementalGlyphMapForCalibri'),
  trebuchet: lookupTable('getSupplementalGlyphMapForTrebuchetMS'),
};
const macGlyphOrder = arrayConst('MacStandardGlyphOrdering');
// The CFF standard strings and predefined charsets (Adobe Technical Note 5176, appendices A and C).
const cffStrings = arrayConst('CFFStandardStrings');
const cffCharsets = Object.fromEntries(['ISOAdobeCharset', 'ExpertCharset', 'ExpertSubsetCharset'].map((n) => [n, arrayConst(n)]));

// Widths by glyph name from each AFM file: "C code ; WX width ; N name ; ...".
const metrics = {};
for (const file of readdirSync(afmDir).filter((f) => f.endsWith('.afm'))) {
  const name = path.basename(file, '.afm');
  const widths = {};
  for (const line of readFileSync(path.join(afmDir, file), 'latin1').split('\n')) {
    const wx = line.match(/WX\s+(-?\d+)/);
    const n = line.match(/;\s*N\s+(\S+)/);
    if (line.startsWith('C ') && wx && n) widths[n[1]] = Number(wx[1]);
  }
  // Courier's widths are all the same: kept as one number.
  const values = new Set(Object.values(widths));
  metrics[name] = values.size === 1 ? [...values][0] : widths;
}

// Glyph names to code points, as one string of "name:hex" pairs, to keep the file small.
const packGlyphs = (map) => Object.entries(map).map(([k, v]) => `${k}:${v.toString(16)}`).join(' ');

const out = `// Generated by tools/make-read-data.mjs: don't edit by hand.
//
// The standard encodings (PDF 32000-1 Annex D), glyph names to Unicode, the font-name tables, CFF
// strings and charsets, standard glyph orders and bidirectional types, as transcribed in Mozilla's
// pdf.js, Copyright Mozilla Foundation, Apache License 2.0 (read/LICENSE-pdf.js.txt). Glyph names
// to Unicode build on Adobe's Glyph List (Copyright 2002-2019 Adobe, BSD 3-Clause; its licence is
// in read/NOTICES.md). The 14 standard fonts' widths are from Adobe's Core 14 AFM files:
// "Copyright (c) 1985, 1987, 1989, 1990, 1997 Adobe Systems Incorporated. All Rights Reserved.
// This file and the 14 PostScript(R) AFM files it accompanies may be used, copied, and distributed
// for any purpose and without charge, with or without modification, provided that all copyright
// notices are retained; that the AFM files are not distributed without this file; that all
// modifications to this file or any of the AFM files are prominently noted in the modified
// file(s); and that this paragraph is not removed." Modified: only each glyph's width is kept.

export const ENCODINGS = ${JSON.stringify(encodings)};

const unpack = (s) => Object.fromEntries(s.split(' ').map((p) => { const i = p.lastIndexOf(':'); return [p.slice(0, i), parseInt(p.slice(i + 1), 16)]; }));
let glyphs = null;
let dingbats = null;
export const glyphsUnicode = () => (glyphs ??= unpack(${JSON.stringify(packGlyphs(glyphs))}));
export const dingbatsUnicode = () => (dingbats ??= unpack(${JSON.stringify(packGlyphs(dingbats))}));

export const STD_FONT_MAP = ${JSON.stringify(stdFontMap)};
export const NON_STD_FONT_MAP = ${JSON.stringify(nonStdFontMap)};
export const SERIF_FONTS = new Set(${JSON.stringify(serifFonts)});
export const SYMBOLS_FONTS = new Set(${JSON.stringify(symbolsFonts)});
export const SPECIAL_PUA = ${JSON.stringify(specialPua)};
export const METRICS = ${JSON.stringify(metrics)};

// Glyph indexes to code points (see the generator), each as "index:hex" pairs.
const unpackGlyphMap = (s) => new Map(s.split(' ').map((p) => p.split(':')).map(([k, v]) => [+k, parseInt(v, 16)]));
const glyphMaps = {};
const packedGlyphMaps = ${JSON.stringify(Object.fromEntries(Object.entries(glyphMaps).map(([k, m]) => [k, Object.entries(m).map(([g, u]) => `${g}:${u.toString(16)}`).join(' ')])))};
export const glyphMap = (name) => (glyphMaps[name] ??= unpackGlyphMap(packedGlyphMaps[name]));

// The Macintosh standard glyph order, for TrueType 'post' tables.
export const MAC_GLYPH_ORDER = ${JSON.stringify(macGlyphOrder)};

// CFF fonts' standard strings (glyph names 0 to 390) and predefined charsets, by name.
export const CFF_STANDARD_STRINGS = ${JSON.stringify(cffStrings)};
export const CFF_CHARSETS = ${JSON.stringify(cffCharsets)};

// Bidirectional character types for U+0000 to U+00FF and U+0600 to U+06FF.
export const BIDI_BASE = ${JSON.stringify(bidiBase)};
export const BIDI_ARABIC = ${JSON.stringify(bidiArabic)};
`;
const target = new URL('../read/data.js', import.meta.url);
writeFileSync(target, out);
console.log(`Wrote ${target.pathname}: ${(out.length / 1024).toFixed(0)} KB, ${Object.keys(glyphs).length} glyph names, ${Object.keys(metrics).length} fonts' metrics.`);
